# ============================================================
# CLEAN GEMINI RESPONSE
# ============================================================

def clean_json_response(response_text: str) -> str:
    """
    Remove Markdown code fences if Gemini returns JSON
    inside ```json ... ``` blocks.
    """

    response_text = response_text.strip()

    response_text = re.sub(
        r"^```json\s*",
        "",
        response_text,
        flags=re.IGNORECASE,
    )

    response_text = re.sub(
        r"^```\s*",
        "",
        response_text,
    )

    response_text = re.sub(
        r"\s*```$",
        "",
        response_text,
    )

    return response_text.strip()


# ============================================================
# EXTRACT JSON OBJECT FROM RESPONSE
# ============================================================

def extract_json_object(text: str) -> str:
    """
    Extract the JSON object from Gemini's response.

    This provides extra protection in case Gemini returns
    a small amount of text before or after the JSON.
    """

    text = text.strip()

    first_brace = text.find("{")
    last_brace = text.rfind("}")

    if first_brace == -1 or last_brace == -1:
        raise ValueError(
            "No valid JSON object found in Gemini response."
        )

    return text[first_brace:last_brace + 1]


# ============================================================
# VALIDATE GENERATED DATA
# ============================================================

def validate_generated_data(data: dict) -> dict:
    """
    Validate the complete structure generated by Gemini.
    """

    required_top_level_fields = [
        "summary",
        "preparationGuide",
        "flashcards",
        "interviewQuestions",
        "quiz",
    ]

    for field in required_top_level_fields:

        if field not in data:
            raise ValueError(
                f"Gemini response is missing '{field}'."
            )

    # ========================================================
    # SUMMARY
    # ========================================================

    if not isinstance(
        data["summary"],
        str,
    ):
        raise ValueError(
            "'summary' must be a string."
        )

    if not data["summary"].strip():
        raise ValueError(
            "'summary' cannot be empty."
        )

    # ========================================================
    # PREPARATION GUIDE
    # ========================================================

    preparation_guide = data[
        "preparationGuide"
    ]

    if not isinstance(
        preparation_guide,
        list,
    ):
        raise ValueError(
            "'preparationGuide' must be a list."
        )

    if len(preparation_guide) < 5:
        raise ValueError(
            "Preparation guide must contain "
            "at least 5 steps."
        )

    for index, item in enumerate(
        preparation_guide,
        start=1,
    ):

        if not isinstance(item, dict):
            raise ValueError(
                f"Preparation guide item {index} "
                "must be an object."
            )

        required_fields = [
            "step",
            "title",
            "description",
            "priority",
        ]

        for field in required_fields:

            if field not in item:
                raise ValueError(
                    f"Preparation guide item {index} "
                    f"is missing '{field}'."
                )

    # ========================================================
    # FLASHCARDS
    # ========================================================

    flashcards = data["flashcards"]

    if not isinstance(
        flashcards,
        list,
    ):
        raise ValueError(
            "'flashcards' must be a list."
        )

    if len(flashcards) < 10:
        raise ValueError(
            "At least 10 flashcards are required."
        )

    for index, card in enumerate(
        flashcards,
        start=1,
    ):

        if not isinstance(card, dict):
            raise ValueError(
                f"Flashcard {index} "
                "must be an object."
            )

        required_fields = [
            "id",
            "question",
            "answer",
        ]

        for field in required_fields:

            if field not in card:
                raise ValueError(
                    f"Flashcard {index} "
                    f"is missing '{field}'."
                )

    # ========================================================
    # INTERVIEW QUESTIONS
    # ========================================================

    interview_questions = data[
        "interviewQuestions"
    ]

    if not isinstance(
        interview_questions,
        list,
    ):
        raise ValueError(
            "'interviewQuestions' must be a list."
        )

    if len(interview_questions) < 10:
        raise ValueError(
            "At least 10 interview questions "
            "are required."
        )

    for index, question in enumerate(
        interview_questions,
        start=1,
    ):

        if not isinstance(
            question,
            dict,
        ):
            raise ValueError(
                f"Interview question {index} "
                "must be an object."
            )

        required_fields = [
            "id",
            "difficulty",
            "question",
            "answer",
            "keyPoints",
        ]

        for field in required_fields:

            if field not in question:
                raise ValueError(
                    f"Interview question {index} "
                    f"is missing '{field}'."
                )

        if not isinstance(
            question["keyPoints"],
            list,
        ):
            raise ValueError(
                f"Interview question {index} "
                "'keyPoints' must be a list."
            )

    # ========================================================
    # QUIZ
    # ========================================================

    quiz = data["quiz"]

    if not isinstance(
        quiz,
        list,
    ):
        raise ValueError(
            "'quiz' must be a list."
        )

    if len(quiz) < 10:
        raise ValueError(
            "At least 10 quiz questions "
            "are required."
        )

    for index, question in enumerate(
        quiz,
        start=1,
    ):

        if not isinstance(
            question,
            dict,
        ):
            raise ValueError(
                f"Quiz question {index} "
                "must be an object."
            )

        required_fields = [
            "id",
            "difficulty",
            "question",
            "options",
            "correctAnswerIndex",
            "explanation",
        ]

        for field in required_fields:

            if field not in question:
                raise ValueError(
                    f"Quiz question {index} "
                    f"is missing '{field}'."
                )

        # Validate difficulty

        difficulty = question[
            "difficulty"
        ].lower()

        if difficulty not in [
            "easy",
            "medium",
            "hard",
        ]:
            raise ValueError(
                f"Quiz question {index} "
                f"has invalid difficulty."
            )

        # Validate options

        options = question[
            "options"
        ]

        if not isinstance(
            options,
            list,
        ):
            raise ValueError(
                f"Quiz question {index} "
                "'options' must be a list."
            )

        if len(options) != 4:
            raise ValueError(
                f"Quiz question {index} "
                "must have exactly 4 options."
            )

        # Validate correct answer

        correct_index = question[
            "correctAnswerIndex"
        ]

        if not isinstance(
            correct_index,
            int,
        ):
            raise ValueError(
                f"Quiz question {index} "
                "'correctAnswerIndex' must "
                "be an integer."
            )

        if correct_index < 0 or correct_index > 3:
            raise ValueError(
                f"Quiz question {index} "
                "'correctAnswerIndex' must "
                "be between 0 and 3."
            )

    return data


