# ============================================================
# GENERATE STUDY MATERIAL USING GEMINI
# ============================================================

def generate_from_notes(notes: str) -> dict:

    notes = notes.strip()

    if not notes:
        raise HTTPException(
            status_code=400,
            detail=(
                "Study material cannot be empty."
            ),
        )

    word_count = len(
        notes.split()
    )

    if word_count < 10:
        raise HTTPException(
            status_code=400,
            detail=(
                "Please provide at least "
                "10 words of study material."
            ),
        )

    if word_count > MAX_WORDS:
        raise HTTPException(
            status_code=400,
            detail=(
                f"Study material cannot exceed "
                f"{MAX_WORDS} words."
            ),
        )

    prompt = build_prompt(
        notes
    )

    # ========================================================
    # CALL GEMINI
    # ========================================================

    try:

        response = client.models.generate_content(
            model=GEMINI_MODEL,
            contents=prompt,
        )

    except Exception as e:

        print(
            "Gemini API error:",
            repr(e),
        )

        raise HTTPException(
            status_code=500,
            detail=(
                "Failed to generate study material "
                "using Gemini. Please check your "
                "API key, model availability, "
                "and API quota."
            ),
        )

    # ========================================================
    # EXTRACT RESPONSE
    # ========================================================

    try:

        ai_text = response.text

        if not ai_text:
            raise ValueError(
                "Gemini returned an empty response."
            )

        ai_text = clean_json_response(
            ai_text
        )

        ai_text = extract_json_object(
            ai_text
        )

    except Exception as e:

        print(
            "Gemini response extraction error:",
            repr(e),
        )

        raise HTTPException(
            status_code=500,
            detail=(
                "Gemini returned an empty or "
                "invalid response."
            ),
        )

    # ========================================================
    # PARSE JSON
    # ========================================================

    try:

        generated_data = json.loads(
            ai_text
        )

    except json.JSONDecodeError as e:

        print(
            "JSON parsing error:",
            repr(e),
        )

        print(
            "Raw Gemini response:",
            ai_text,
        )

        raise HTTPException(
            status_code=500,
            detail=(
                "Gemini returned invalid JSON. "
                "Please try again."
            ),
        )

    # ========================================================
    # VALIDATE DATA
    # ========================================================

    try:

        generated_data = validate_generated_data(
            generated_data
        )

    except ValueError as e:

        print(
            "Generated data validation error:",
            repr(e),
        )

        raise HTTPException(
            status_code=500,
            detail=str(e),
        )

    # ========================================================
    # RETURN RESPONSE
    # ========================================================

    return {
        "message": (
            "Study material generated successfully."
        ),
        "word_count": word_count,
        "summary": generated_data[
            "summary"
        ],
        "preparationGuide": generated_data[
            "preparationGuide"
        ],
        "flashcards": generated_data[
            "flashcards"
        ],
        "interviewQuestions": generated_data[
            "interviewQuestions"
        ],
        "quiz": generated_data[
            "quiz"
        ],
    }


# ============================================================
# EXTRACT TEXT FROM PDF
# ============================================================

def extract_pdf_text(
    file_bytes: bytes,
) -> str:

    import io

    pdf_stream = io.BytesIO(
        file_bytes
    )

    reader = PdfReader(
        pdf_stream
    )

    pages_text = []

    for page in reader.pages:

        text = page.extract_text()

        if text:
            pages_text.append(
                text
            )

    return "\n".join(
        pages_text
    ).strip()


# ============================================================
# EXTRACT TEXT FROM DOCX
# ============================================================

def extract_docx_text(
    file_bytes: bytes,
) -> str:

    import io

    doc_stream = io.BytesIO(
        file_bytes
    )

    document = Document(
        doc_stream
    )

    paragraphs = []

    for paragraph in document.paragraphs:

        text = paragraph.text.strip()

        if text:
            paragraphs.append(
                text
            )

    # Also extract table content

    for table in document.tables:

        for row in table.rows:

            row_text = []

            for cell in row.cells:

                cell_text = (
                    cell.text.strip()
                )

                if cell_text:
                    row_text.append(
                        cell_text
                    )

            if row_text:

                paragraphs.append(
                    " | ".join(
                        row_text
                    )
                )

    return "\n".join(
        paragraphs
    ).strip()


# ============================================================
# EXTRACT TEXT FROM TXT
# ============================================================

def extract_txt_text(
    file_bytes: bytes,
) -> str:

    try:

        return file_bytes.decode(
            "utf-8"
        ).strip()

    except UnicodeDecodeError:

        return file_bytes.decode(
            "latin-1"
        ).strip()


# ============================================================
# EXTRACT TEXT FROM UPLOADED FILE
# ============================================================

def extract_file_text(
    filename: str,
    file_bytes: bytes,
) -> str:

    extension = Path(
        filename
    ).suffix.lower()

    if extension == ".pdf":

        return extract_pdf_text(
            file_bytes
        )

    if extension == ".docx":

        return extract_docx_text(
            file_bytes
        )

    if extension == ".txt":

        return extract_txt_text(
            file_bytes
        )

    raise HTTPException(
        status_code=400,
        detail=(
            "Unsupported file type. "
            "Please upload PDF, DOCX, or TXT."
        ),
    )


