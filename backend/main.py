# FILE UPLOAD GENERATION ENDPOINT
# ============================================================

@app.post(
    "/api/generate-file"
)
async def generate_from_file(
    file: UploadFile = File(...),
):

    # ========================================================
    # VALIDATE FILE NAME
    # ========================================================

    if not file.filename:

        raise HTTPException(
            status_code=400,
            detail=(
                "Uploaded file must have a filename."
            ),
        )

    extension = Path(
        file.filename
    ).suffix.lower()

    if extension not in ALLOWED_EXTENSIONS:

        raise HTTPException(
            status_code=400,
            detail=(
                "Unsupported file type. "
                "Please upload PDF, DOCX, or TXT."
            ),
        )

    # ========================================================
    # READ FILE
    # ========================================================

    try:

        file_bytes = await file.read()

    except Exception as e:

        print(
            "File reading error:",
            repr(e),
        )

        raise HTTPException(
            status_code=400,
            detail=(
                "Could not read the uploaded file."
            ),
        )

    # ========================================================
    # CHECK FILE SIZE
    # ========================================================

    max_file_size = (
        10 * 1024 * 1024
    )

    if len(file_bytes) > max_file_size:

        raise HTTPException(
            status_code=400,
            detail=(
                "File size must be less than "
                "10 MB."
            ),
        )

    if len(file_bytes) == 0:

        raise HTTPException(
            status_code=400,
            detail=(
                "Uploaded file is empty."
            ),
        )

    # ========================================================
    # EXTRACT TEXT
    # ========================================================

    try:

        extracted_text = extract_file_text(
            file.filename,
            file_bytes,
        )

    except HTTPException:

        raise

    except Exception as e:

        print(
            "Text extraction error:",
            repr(e),
        )

        raise HTTPException(
            status_code=500,
            detail=(
                "Failed to extract text from "
                "the uploaded file."
            ),
        )

    # ========================================================
    # VALIDATE EXTRACTED TEXT
    # ========================================================

    if not extracted_text.strip():

        raise HTTPException(
            status_code=400,
            detail=(
                "Could not extract readable text "
                "from the uploaded file."
            ),
        )

    # ========================================================
    # LIMIT WORD COUNT
    # ========================================================

    words = extracted_text.split()

    if len(words) > MAX_WORDS:

        extracted_text = " ".join(
            words[:MAX_WORDS]
        )

    # ========================================================
    # GENERATE AI CONTENT
    # ========================================================

    result = generate_from_notes(
        extracted_text
    )

    # ========================================================
    # ADD FILE INFORMATION
    # ========================================================

    result["source"] = {
        "type": "file",
        "filename": file.filename,
        "extension": extension,
    }

    return result